#!/usr/bin/env python3
"""P5C Wave 1 — Synthetic Company Generator (stdlib only).

Generates deterministic synthetic financial-company JSON fixtures that exercise
specific edge cases (holding segment conflicts, IAS-29 anomalies, NIM jumps,
FX shocks, conflicting disclosures, missing metrics, leverage stress, etc.).

Usage:
    python3 scripts/synth_generator.py --case <case_id|all> [--seed N] [--out-dir DIR]

Exit codes:
    0  success
    2  bad arguments
    3  generation error

Constraints:
    - Python stdlib ONLY. No requests/httpx/numpy/pandas. No python-services
      imports. Self-contained CLI.
    - Deterministic: identical (case_id, seed) → identical JSON (modulo
      generated_at timestamp).
    - Output JSON conforms to evals/synthetic/schema/synthetic_company.schema.json.
    - Every fixture sets synthetic_fixture: true and includes a _warning
      field clearly marking the file as non-authoritative test data.
"""

