# ---------------------------------------------------------------------------
# Wrapper that adds the schema-mandated envelope fields
# ---------------------------------------------------------------------------

def generate_company(case_id: str, seed: int) -> dict[str, Any]:
    if case_id not in GENERATORS:
        raise ValueError(f"Unknown case_id: {case_id}")
    rng = random.Random(seed)
    inner = GENERATORS[case_id](rng)
    return {
        "_warning": WARNING_TEXT,
        "synthetic_fixture": True,
        "synthetic_id": f"SYNTH_{case_id.upper()}",
        "case_id": case_id,
        "sector": inner["sector"],
        "induced_issues": inner["induced_issues"],
        "financial_statements": inner["financial_statements"],
        "disclosures": inner["disclosures"],
        "expected_agent_behavior": inner["expected_agent_behavior"],
        "generator": {
            "script_version": SCRIPT_VERSION,
            "seed": seed,
            "generated_at": datetime.now(timezone.utc).isoformat().replace("+00:00", "Z"),
        },
    }


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def _write(out_path: Path, payload: dict[str, Any]) -> None:
    out_path.parent.mkdir(parents=True, exist_ok=True)
    with out_path.open("w", encoding="utf-8") as f:
        json.dump(payload, f, ensure_ascii=False, indent=2)
        f.write("\n")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="synth_generator.py",
        description=(
            "P5C synthetic company generator. Stdlib-only. Deterministic with "
            "--seed. Produces JSON fixtures that conform to "
            "evals/synthetic/schema/synthetic_company.schema.json."
        ),
    )
    parser.add_argument(
        "--case",
        required=True,
        help="Case id from the registry, or 'all' to generate every case.",
    )
    parser.add_argument(
        "--seed",
        type=int,
        default=42,
        help="RNG seed for deterministic output (default 42).",
    )
    parser.add_argument(
        "--out-dir",
        default="evals/synthetic",
        help="Output directory for JSON fixtures (default evals/synthetic).",
    )

    try:
        args = parser.parse_args(argv)
    except SystemExit as exit_:
        # argparse prints its own error; map invalid argv to exit 2.
        return 2 if exit_.code != 0 else 0

    targets: list[str]
    if args.case == "all":
        targets = list(CASE_IDS)
    elif args.case in CASE_IDS:
        targets = [args.case]
    else:
        sys.stderr.write(
            f"[synth_generator] Unknown --case '{args.case}'. "
            f"Valid: {', '.join(CASE_IDS + ['all'])}\n"
        )
        return 2

    out_dir = Path(args.out_dir)

    for case_id in targets:
        try:
            payload = generate_company(case_id, args.seed)
        except Exception as exc:  # noqa: BLE001 — boundary
            sys.stderr.write(f"[synth_generator] Generation failed for {case_id}: {exc}\n")
            return 3
        out_path = out_dir / f"{case_id}.json"
        try:
            _write(out_path, payload)
        except OSError as exc:
            sys.stderr.write(f"[synth_generator] Write failed for {out_path}: {exc}\n")
            return 3
        sys.stdout.write(f"[synth_generator] wrote {out_path}\n")

    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
